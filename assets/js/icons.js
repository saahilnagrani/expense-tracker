export function icon(name, size = 24) {
  const body = P[name];
  if (!body) return "";
  return `<svg class="ic" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`;
}

// Fill any element with a data-ic="<name>" attribute (used for static markup).
export function hydrateIcons(root = document) {
  root.querySelectorAll("[data-ic]").forEach((el) => {
    const size = +el.getAttribute("data-ic-size") || 24;
    el.innerHTML = icon(el.getAttribute("data-ic"), size);
  });
}
